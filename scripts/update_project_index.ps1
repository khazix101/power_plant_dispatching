[CmdletBinding()]
param(
    [string]$Root = (Split-Path -Parent $PSScriptRoot),
    [string]$OutputPath = ""
)

$ErrorActionPreference = "Stop"
if ([string]::IsNullOrWhiteSpace($OutputPath)) {
    $OutputPath = Join-Path $Root "docs\PROJECT_CONTEXT.md"
}

$excluded = @(
    ".git", ".opencode", "Dataset", "output", "local", "tmp",
    "__pycache__", ".pytest_cache", ".venv", "venv", "env"
)
$rootPath = (Resolve-Path $Root).Path
$outputFullPath = [System.IO.Path]::GetFullPath($OutputPath)

function Get-RelativePath([string]$Path) {
    return [System.IO.Path]::GetRelativePath($rootPath, $Path).Replace("\", "/")
}

function Test-Excluded([string]$RelativePath) {
    $parts = $RelativePath.Split('/')
    foreach ($part in $parts) {
        if ($excluded -contains $part) { return $true }
    }
    return $false
}

$now = Get-Date -Format "yyyy-MM-dd HH:mm:ss zzz"
$branch = (git -C $rootPath branch --show-current 2>$null).Trim()
if ([string]::IsNullOrWhiteSpace($branch)) { $branch = "(detached HEAD)" }
$status = @(git -C $rootPath status --short 2>$null)

$files = Get-ChildItem -LiteralPath $rootPath -Recurse -File -Force |
    Where-Object {
        $relative = Get-RelativePath $_.FullName
        -not (Test-Excluded $relative) -and $_.FullName -ne $outputFullPath
    } |
    Sort-Object FullName

$topLevel = Get-ChildItem -LiteralPath $rootPath -Force |
    Where-Object { $_.Name -notin $excluded -and $_.Name -ne ".cursor" } |
    Sort-Object Name

$lines = [System.Collections.Generic.List[string]]::new()
$lines.Add("# Project Context")
$lines.Add("")
$lines.Add("> Generated by ``scripts/update_project_index.ps1``. Last refresh: $now")
$lines.Add("")
$lines.Add("## Repository")
$lines.Add("")
$lines.Add("- Root: ``$rootPath``")
$lines.Add("- Branch: ``$branch``")
$lines.Add("- Working tree entries: $($status.Count) changed, added, or deleted")
$lines.Add("")
$lines.Add("## Top-level map")
$lines.Add("")
foreach ($item in $topLevel) {
    $kind = if ($item.PSIsContainer) { "directory" } else { "file" }
    $lines.Add("- ``$($item.Name)`` ($kind)")
}
$lines.Add("")
$lines.Add("## Tracked source and documentation files")
$lines.Add("")
foreach ($file in $files) {
    $relative = Get-RelativePath $file.FullName
    $lines.Add("- ``$relative``")
}
$lines.Add("")
$lines.Add("## Existing runnable entry points")
$lines.Add("")
$entryPoints = $files | Where-Object {
    $_.Extension -in @(".py", ".ps1", ".bat", ".sh") -and
    ($_.Name -match "^(run|main|train|build|calibrate|decode|update|test)" -or $_.DirectoryName -match "scripts|parper")
}
if ($entryPoints.Count -eq 0) {
    $lines.Add("- No conventional entry point detected; inspect ``scripts/`` and ``parper/``.")
} else {
    foreach ($file in $entryPoints) { $lines.Add("- ``$(Get-RelativePath $file.FullName)``") }
}
$lines.Add("")
$lines.Add("## Research workspace summary")
$lines.Add("")
$localPaperPath = Join-Path $rootPath "local\论文"
if (Test-Path -LiteralPath $localPaperPath) {
    $lines.Add("- ``local/论文/`` exists and is intentionally excluded from the compact source tree.")
    $paperFiles = Get-ChildItem -LiteralPath $localPaperPath -File -Force | Sort-Object Name
    foreach ($file in $paperFiles) { $lines.Add("- ``local/论文/$($file.Name)``") }
} else {
    $lines.Add("- ``local/论文/`` not found at refresh time.")
}
$lines.Add("")
$lines.Add("## Git status snapshot")
$lines.Add("")
if ($status.Count -eq 0) {
    $lines.Add("- Working tree clean at refresh time.")
} else {
    foreach ($line in $status) { $lines.Add("- ``$line``") }
}
$lines.Add("")
$lines.Add("## Excluded from compact tree")
$lines.Add("")
$lines.Add("- ``Dataset/``: local or potentially sensitive data")
$lines.Add("- ``output/`` and ``tmp/``: generated experiment output and scratch files")
$lines.Add("- ``local/``: local research notes, papers, and generated materials")
$lines.Add("- ``.opencode/`` and caches: tool/runtime files")
$lines.Add("")
$lines.Add("## Refresh command")
$lines.Add("")
$lines.Add("````powershell")
$lines.Add("pwsh -NoProfile -File scripts/update_project_index.ps1")
$lines.Add("````")

$parent = Split-Path -Parent $outputFullPath
New-Item -ItemType Directory -Force -Path $parent | Out-Null
[System.IO.File]::WriteAllLines($outputFullPath, $lines, [System.Text.UTF8Encoding]::new($false))
Write-Output "Updated $outputFullPath"
